static vgui::DHANDLE<FlyoutMenu> s_ActiveFlyout;

static const char *ButtonCommand( vgui::Button *button )
{
	KeyValues *command = button ? button->GetCommand() : NULL;
	return command ? command->GetString( "command", "" ) : "";
}

vgui::Panel *CreateBaseModFlyoutControl( vgui::Panel *parent, const char *className )
{
	if ( !Q_stricmp( className, "FlyoutMenu" ) ) return new FlyoutMenu( parent, "" );
	if ( !Q_stricmp( className, "DropDownMenu" ) ) return new DropDownMenu( parent, "" );
	return NULL;
}

FlyoutMenu::FlyoutMenu( vgui::Panel *parent, const char *name ) : BaseClass( parent, name ),
	m_pListener( NULL ), m_OffsetX( 0 ), m_OffsetY( 0 ), m_OriginalTall( 0 ),
	m_bOnlyActiveUser( false ), m_bExpandUp( false ), m_bWideAtOpen( false ),
	m_bStandalonePositioning( false ), m_bDirectCommandTarget( false ),
	m_bNoBlindNavigation( false ), m_bOpaque( false ), m_bInitialFocusOverride( false ), m_pRowTemplate( NULL )
{
	SetProportional( true );
}

FlyoutMenu::~FlyoutMenu()
{
	if ( s_ActiveFlyout.Get() == this ) s_ActiveFlyout = NULL;
	if ( m_pRowTemplate ) m_pRowTemplate->deleteThis();
}

vgui::Panel *FlyoutMenu::CreateControlByName( const char *name )
{
	if ( !Q_stricmp( name, "L4D360HybridButton" ) ) return new L4D360HybridButton( this, "" );
	vgui::Panel *control = CreateBaseModFlyoutControl( this, name );
	return control ? control : BaseClass::CreateControlByName( name );
}

void FlyoutMenu::ApplySettings( KeyValues *data )
{
	BaseClass::ApplySettings( data );
	const char *resource = data->GetString( "ResourceFile", NULL );
	if ( resource && *resource )
	{
		m_Resource = resource;
		LoadMenu( resource );
	}
	m_OffsetX = m_OffsetY = 0;
	if ( !m_bInitialFocusOverride ) m_InitialFocus = data->GetString( "InitialFocus", "" );
	m_bOnlyActiveUser = data->GetBool( "OnlyActiveUser", false );
	m_bExpandUp = data->GetBool( "ExpandUp", false );
	m_bStandalonePositioning = data->GetBool( "StandalonePositioning", false );
	m_bDirectCommandTarget = data->GetBool( "DirectCommandTarget", false );
}

void FlyoutMenu::LoadControlSettings( const char *resource, const char *pathID, KeyValues *preloaded, KeyValues *conditions )
{
	// All original files come through the existing mounted-resource evaluator.
	// pathID does not establish a second content search path for this family.
	LoadMenuData( resource, preloaded, conditions );
}

bool FlyoutMenu::LoadMenu( const char *resource, KeyValues *conditions )
{
	return LoadMenuData( resource, NULL, conditions );
}

bool FlyoutMenu::LoadMenuData( const char *resource, KeyValues *preloaded, KeyValues *conditions )
{
	const char *countText = StringAfterPrefix( resource, "FlmChapterXXautogenerated_" );
	const char *filename = countText ? Q_strstr( countText, "/" ) : resource;
	if ( !filename ) return false;
	if ( countText ) ++filename;
	KeyValues::AutoDelete data( preloaded ? preloaded->MakeCopy() : new KeyValues( "" ) );
	if ( !preloaded && !LoadTerrorUiResource( data, filename ) ) return false;
	if ( countText )
	{
		KeyValues *row = data->FindKey( "BtnChapter" );
		const int count = atoi( countText );
		if ( row && count > 0 )
		{
			KeyValues *height = data->FindKey( "PnlBackground/tall" );
			if ( height ) height->SetInt( NULL, height->GetInt() + ( count - 1 ) * row->GetInt( "tall" ) );
			for ( int i = 1; i <= count; ++i )
			{
				KeyValues *copy = row->MakeCopy();
				copy->SetName( CFmtStr( "%s%d", row->GetName(), i ) );
				copy->SetString( "navUp", CFmtStr( "%s%d", row->GetName(), ( i + count - 2 ) % count + 1 ) );
				copy->SetString( "navDown", CFmtStr( "%s%d", row->GetName(), i % count + 1 ) );
				copy->SetInt( "ypos", row->GetInt( "ypos" ) + ( i - 1 ) * row->GetInt( "tall" ) );
				const char *fields[] = { "fieldName", "labelText", "command" };
				for ( int j = 0; j < ARRAYSIZE( fields ); ++j ) copy->SetString( fields[j], CFmtStr( "%s%d", row->GetString( fields[j] ), i ) );
				data->AddSubKey( copy );
			}
			data->RemoveSubKey( row );
			row->deleteThis();
		}
	}
	m_bNoBlindNavigation = data->GetBool( "FlyoutMenuSettings/noblindnavigation", false );
	m_bOpaque = data->GetBool( "FlyoutMenuSettings/solidfill", false );
	const bool noHorizontal = data->GetBool( "FlyoutMenuSettings/noleftrightautonav", false );
	const bool randomize = data->GetBool( "FlyoutMenuSettings/randomizeitems", false );
	if ( m_pRowTemplate ) { m_pRowTemplate->deleteThis(); m_pRowTemplate = NULL; }
	for ( KeyValues *row = data->GetFirstTrueSubKey(); row; row = row->GetNextTrueSubKey() )
	{
		if ( !Q_stricmp( row->GetString( "ControlName" ), "L4D360HybridButton" ) ) { m_pRowTemplate = row->MakeCopy(); break; }
	}
	// FlyoutMenuSettings is metadata, not an unregistered VGUI child control.
	KeyValues *settings = data->FindKey( "FlyoutMenuSettings" );
	if ( settings ) { data->RemoveSubKey( settings ); settings->deleteThis(); }
	BaseClass::LoadControlSettings( filename, "GAME", data, conditions );
	ApplyAutoNavigation( noHorizontal );
	if ( randomize ) RandomizeItems();
	ApplySchemeSettings( vgui::scheme()->GetIScheme( GetScheme() ) );
	return true;
}

void FlyoutMenu::ApplyAutoNavigation( bool disabled )
{
	if ( disabled ) return;
	for ( int i = 0; i < GetChildCount(); ++i )
	{
		vgui::Button *button = dynamic_cast<vgui::Button *>( GetChild( i ) );
		if ( !button ) continue;
		if ( !*button->GetNavLeftName() ) button->SetNavLeft( button->GetNavUpName() );
		if ( !*button->GetNavRightName() ) button->SetNavRight( button->GetNavDownName() );
	}
}

void FlyoutMenu::RandomizeItems()
{
	// G2E630 permutes only visible, enabled button payloads; row geometry and
	// navigation do not move. Copy commands before SetCommand takes ownership.
	struct Payload { wchar_t text[128]; KeyValues *command; };
	CUtlVector<vgui::Button *> rows;
	CUtlVector<Payload> payload;
	for ( int i = 0; i < GetChildCount(); ++i )
	{
		vgui::Button *button = dynamic_cast<vgui::Button *>( GetChild( i ) );
		if ( !button || !button->IsVisible() || !button->IsEnabled() ) continue;
		rows.AddToTail( button );
		Payload &item = payload[payload.AddToTail()];
		button->GetText( item.text, ARRAYSIZE( item.text ) );
		item.command = button->GetCommand() ? button->GetCommand()->MakeCopy() : NULL;
	}
	for ( int i = 0; i < payload.Count(); ++i )
	{
		const int index = RandomInt( 0, rows.Count() - 1 );
		rows[index]->SetText( payload[i].text );
		rows[index]->SetCommand( payload[i].command );
		rows.Remove( index );
	}
}

void FlyoutMenu::ApplySchemeSettings( vgui::IScheme *scheme )
{
	// Native G2D8D0 intentionally does not paint the resource's PnlBackground.
	// Its full width and 70% PC height establish the gradient panel's bounds.
	if ( scheme ) ResizeFromBackground();
	SetPaintBackgroundEnabled( true );
}

void FlyoutMenu::ResizeFromBackground()
{
	vgui::Panel *background = FindChildByName( "PnlBackground" );
	if ( !background ) return;
	const int wide = background->GetWide();
	const int tall = (int)( background->GetTall() * 0.7f );
	if ( wide != GetWide() || tall != GetTall() )
	{
		SetSize( wide, tall );
		for ( int i = 0; i < GetChildCount(); ++i )
		{
			vgui::Button *button = dynamic_cast<vgui::Button *>( GetChild( i ) );
			if ( !button ) continue;
			int x, y; button->GetPos( x, y );
			button->SetPos( x, (int)( y * 0.7f ) );
		}
	}
	background->SetVisible( false );
}

void FlyoutMenu::SetBackgroundHeight( int tall )
{
	vgui::Panel *background = FindChildByName( "PnlBackground" );
	if ( background ) background->SetTall( vgui::scheme()->GetProportionalScaledValue( tall ) );
}

void FlyoutMenu::PaintBackground()
{
	// G2E040: fixed two-pixel edge gradients, not a proportional replacement.
	vgui::ISurface *surface = vgui::surface();
	const int half = GetWide() / 2;
	const int span = m_bWideAtOpen ? (int)( half * 0.7f ) : GetWide() / 4;
	const int alpha = m_bWideAtOpen ? 245 : 220;
	surface->DrawSetColor( Color( 0, 0, 0, 255 ) );
	surface->DrawFilledRect( 0, 0, half, GetTall() );
	if ( m_bOpaque ) surface->DrawFilledRect( half, 0, GetWide(), GetTall() );
	else
	{
		surface->DrawFilledRectFade( half, 0, half + span, GetTall(), 255, alpha, true );
		surface->DrawFilledRectFade( half + span, 0, GetWide(), GetTall(), alpha, 0, true );
	}
	vgui::IScheme *scheme = vgui::scheme()->GetIScheme( GetScheme() );
	surface->DrawSetColor( scheme->GetColor( "HybridButton.BorderColor", Color( 0, 0, 0, 255 ) ) );
	surface->DrawFilledRectFade( 0, 0, GetWide(), 2, 255, 0, true );
	surface->DrawFilledRectFade( 0, GetTall() - 2, GetWide(), GetTall(), 255, 0, true );
	if ( m_bExpandUp ) surface->DrawFilledRect( 0, 0, 2, GetTall() - m_OriginalTall + 2 );
	else surface->DrawFilledRect( 0, m_OriginalTall - 2, 2, GetTall() );
}

