void FlyoutMenu::OpenMenu( vgui::Panel *parentButton, vgui::Panel *initialFocus, bool reloadResource, vgui::Panel *positionFrom )
{
	if ( s_ActiveFlyout.Get() == this ) { CloseMenu(); return; }
	CloseActiveMenu( this ); // G2E249..256 hands the new flyout to the old close listener.
	if ( reloadResource && !m_Resource.IsEmpty() ) LoadMenu( m_Resource.String() );
	m_ParentButton = parentButton;
	vgui::Panel *anchor = positionFrom ? positionFrom : parentButton;
	if ( anchor )
	{
		int x, y, wide, tall; anchor->GetBounds( x, y, wide, tall );
		if ( anchor->GetParent() && !m_bStandalonePositioning )
		{
			int px, py; anchor->GetParent()->GetPos( px, py ); x += px; y += py;
		}
		int center = 0;
		L4D360HybridButton *hybrid = dynamic_cast<L4D360HybridButton *>( anchor );
		if ( hybrid )
		{
			hybrid->SetOpen();
			m_OriginalTall = hybrid->GetOriginalTall();
			if ( hybrid->GetStyle() != 9 ) center = ( tall - m_OriginalTall ) / 2;
			if ( ( hybrid->GetStyle() == 3 || hybrid->GetStyle() == 9 ) && hybrid->GetWideAtOpen() )
			{
				wide = hybrid->GetWideAtOpen(); m_bWideAtOpen = true;
			}
		}
		if ( m_bExpandUp ) y += m_OriginalTall - GetTall();
		SetPos( x + wide + m_OffsetX, y + center + m_OffsetY );
	}
	else m_OriginalTall = 0;
	vgui::Panel *focus = initialFocus ? initialFocus : FindInitialFocus();
	if ( focus ) focus->NavigateTo();
	else NavigateTo();
	CL4DFooterPanel *footer = GetL4DFooterPanel( this );
	if ( footer )
	{
		int layout = footer->GetButtonLayout(); if ( layout == 1 ) layout = 2;
		footer->SetButtons( FB_BUTTON_A | FB_BUTTON_B, layout, footer->IsHelpTextEnabled() );
		footer->SetButtonText( FB_BUTTON_A, "#L4D360UI_Select" );
		footer->SetButtonText( FB_BUTTON_B, "#L4D360UI_Cancel" );
	}
	s_ActiveFlyout = this;
	SetVisible( true );
	MoveToFront();
}

void FlyoutMenu::CloseMenu( vgui::Panel *returnTo )
{
	s_ActiveFlyout = NULL; // G2D710 clears before child/return-target navigation and listener notification.
	for ( int i = 0; i < GetChildCount(); ++i ) GetChild( i )->NavigateFrom();
	if ( returnTo ) returnTo->NavigateTo();
	SetVisible( false );
	if ( m_pListener ) m_pListener->OnFlyoutMenuClosed( returnTo );
	L4D360HybridButton *hybrid = dynamic_cast<L4D360HybridButton *>( m_ParentButton.Get() );
	if ( hybrid ) hybrid->SetClosed();
}

void FlyoutMenu::OnCommand( const char *command )
{
	vgui::DHANDLE<vgui::Panel> parentButton = m_ParentButton;
	if ( !parentButton.Get() ) { BaseClass::OnCommand( command ); return; }
	CloseMenu( parentButton.Get() );
	vgui::Panel *target = m_bDirectCommandTarget ? parentButton.Get() : parentButton->GetParent();
	if ( target ) target->OnCommand( command );
}

void FlyoutMenu::OnKeyCodePressed( vgui::KeyCode code )
{
	if ( m_bOnlyActiveUser && GetJoystickForCode( code ) != 0 ) return;
	const vgui::KeyCode key = GetBaseButtonCode( code );
	if ( key == KEY_XBUTTON_B || key == KEY_ESCAPE )
	{
		vgui::surface()->PlaySound( "UI/menu_back.wav" );
		CloseMenu( m_ParentButton.Get() );
		if ( m_pListener ) m_pListener->OnFlyoutMenuCancelled();
		return;
	}
	if ( key == KEY_XBUTTON_Y )
	{
		CL4DFrame *frame = dynamic_cast<CL4DFrame *>( m_pListener );
		if ( frame ) frame->OnKeyCodePressed( code );
		return;
	}
}

vgui::Button *FlyoutMenu::FindChildButtonByCommand( const char *command )
{
	if ( !command ) return NULL;
	for ( int i = 0; i < GetChildCount(); ++i )
	{
		vgui::Button *button = dynamic_cast<vgui::Button *>( GetChild( i ) );
		if ( button && *ButtonCommand( button ) && !Q_stricmp( command, ButtonCommand( button ) ) ) return button;
	}
	return NULL;
}
vgui::Button *FlyoutMenu::FindNextChildButtonByCommand( const char *command )
{
	vgui::Button *button = FindChildButtonByCommand( command );
	return button ? dynamic_cast<vgui::Button *>( button->GetNavDown() ) : NULL;
}
vgui::Button *FlyoutMenu::FindPrevChildButtonByCommand( const char *command )
{
	vgui::Button *button = FindChildButtonByCommand( command );
	return button ? dynamic_cast<vgui::Button *>( button->GetNavUp() ) : NULL;
}

void FlyoutMenu::BeginDynamicRows()
{
	CloseMenu();
	m_DynamicRows.RemoveAll();
	for ( int i = GetChildCount() - 1; i >= 0; --i ) if ( dynamic_cast<vgui::Button *>( GetChild( i ) ) ) delete GetChild( i );
}
L4D360HybridButton *FlyoutMenu::AddDynamicRow( const char *name, const char *text, const char *command, bool enabled )
{
	if ( !m_pRowTemplate ) return NULL;
	KeyValues::AutoDelete row( m_pRowTemplate->MakeCopy() );
	row->SetString( "fieldName", name ); row->SetString( "labelText", text ); row->SetString( "command", command );
	row->SetInt( "enabled", enabled ); row->SetInt( "visible", 1 );
	row->SetInt( "ypos", m_pRowTemplate->GetInt( "ypos" ) + m_DynamicRows.Count() * m_pRowTemplate->GetInt( "tall" ) );
	L4D360HybridButton *button = new L4D360HybridButton( this, name );
	button->ApplySettings( row ); button->AddActionSignalTarget( this );
	m_DynamicRows.AddToTail( button );
	return button;
}
void FlyoutMenu::EndDynamicRows()
{
	for ( int i = 0; i < m_DynamicRows.Count(); ++i )
	{
		L4D360HybridButton *button = m_DynamicRows[i];
		L4D360HybridButton *up = m_DynamicRows[( i + m_DynamicRows.Count() - 1 ) % m_DynamicRows.Count()];
		L4D360HybridButton *down = m_DynamicRows[( i + 1 ) % m_DynamicRows.Count()];
		button->SetNavUp( up ); button->SetNavDown( down );
		button->SetNavLeft( up ); button->SetNavRight( down );
	}
	vgui::Panel *background = FindChildByName( "PnlBackground" );
	if ( background && m_pRowTemplate )
	{
		const int rowTall = vgui::scheme()->GetProportionalScaledValueEx( GetScheme(), m_pRowTemplate->GetInt( "tall" ) );
		background->SetTall( rowTall * m_DynamicRows.Count() + vgui::scheme()->GetProportionalScaledValueEx( GetScheme(), 5 ) );
	}
	if ( m_DynamicRows.Count() ) { m_InitialFocus = m_DynamicRows[0]->GetName(); m_FocusedChild = m_DynamicRows[0]; }
	ResizeFromBackground();
}

DropDownMenu::DropDownMenu( vgui::Panel *parent, const char *name ) : BaseClass( parent, name ),
	m_bShowSelectedText( true ), m_bNoBlindNavigation( false ), m_pOpenCallback( NULL )
{
	m_SelectedCommand[0] = 0;
	SetProportional( true ); SetKeyBoardInputEnabled( true );
}
vgui::Panel *DropDownMenu::CreateControlByName( const char *name )
{
	if ( !Q_stricmp( name, "L4D360HybridButton" ) ) return new L4D360HybridButton( this, "" );
	vgui::Panel *control = CreateBaseModFlyoutControl( this, name );
	return control ? control : BaseClass::CreateControlByName( name );
}
L4D360HybridButton *DropDownMenu::GetButton()
{
	if ( !m_Button.Get() ) m_Button = dynamic_cast<L4D360HybridButton *>( FindChildByName( "BtnDropButton" ) );
	return m_Button.Get();
}
FlyoutMenu *DropDownMenu::GetFlyout()
{
	if ( !m_Flyout.Get() && GetButton() && GetParent() ) m_Flyout = dynamic_cast<FlyoutMenu *>( GetParent()->FindChildByName( ButtonCommand( m_Button.Get() ) ) );
	return m_Flyout.Get();
}
void DropDownMenu::ApplySettings( KeyValues *data )
{
	BaseClass::ApplySettings( data );
	m_Button = dynamic_cast<L4D360HybridButton *>( FindChildByName( "BtnDropButton" ) );
	if ( m_Button.Get() && !HasFocus() && !m_Button->HasFocus() ) m_Button->NavigateFrom();
	const char *command = data->GetString( "command", NULL );
	if ( command ) SetFlyout( command );
	m_bNoBlindNavigation = data->GetBool( "noblindnavigation", false );
	if ( m_Button.Get() )
	{
		int x, y, wide, tall; GetBounds( x, y, wide, tall );
		const int buttonTall = m_Button->GetTall();
		SetBounds( x, y - ( buttonTall - tall ) / 2, wide, buttonTall );
	}
}
void DropDownMenu::SetFlyout( const char *name )
{
	if ( GetButton() ) m_Button->SetCommand( name );
	m_Flyout = GetParent() ? dynamic_cast<FlyoutMenu *>( GetParent()->FindChildByName( name ) ) : NULL;
}
void DropDownMenu::SetShowSelectedText( bool show )
{
	m_bShowSelectedText = show;
	if ( !show ) { m_SelectedCommand[0] = 0; if ( GetButton() ) m_Button->SetCurrentSelection( "" ); }
}
const char *DropDownMenu::GetCurrentSelection() const { return *m_SelectedCommand ? m_SelectedCommand : NULL; }
void DropDownMenu::SetCurrentSelection( const char *command )
{
	if ( !command ) return;
	char source[260], text[260]; Q_strncpy( source, command, sizeof( source ) );
	FlyoutMenu *flyout = GetFlyout();
	vgui::Button *selected = flyout ? flyout->FindChildButtonByCommand( source ) : NULL;
	if ( selected ) selected->GetText( text, sizeof( text ) );
	else Q_strncpy( text, source, sizeof( text ) );
	Q_strncpy( m_SelectedCommand, source, sizeof( m_SelectedCommand ) );
	if ( GetButton() && m_bShowSelectedText ) m_Button->SetCurrentSelection( text );
	if ( GetParent() ) GetParent()->OnCommand( source );
}
void DropDownMenu::OnCommand( const char *command )
{
	if ( command ) m_Flyout = GetParent() ? dynamic_cast<FlyoutMenu *>( GetParent()->FindChildByName( command ) ) : NULL;
	FlyoutMenu *flyout = command ? m_Flyout.Get() : GetFlyout();
	if ( !flyout ) { if ( command ) SetCurrentSelection( command ); return; }
	if ( flyout->IsVisible() ) flyout->CloseMenu( GetButton() );
	else
	{
		flyout->OpenMenu( GetButton(), flyout->FindChildButtonByCommand( GetCurrentSelection() ) );
		if ( m_pOpenCallback ) m_pOpenCallback( this, flyout );
	}
}
void DropDownMenu::CloseDropDown()
{
	FlyoutMenu *flyout = GetFlyout(); if ( flyout && flyout->IsVisible() ) flyout->CloseMenu( GetButton() );
}
void DropDownMenu::ChangeSelection( bool forward )
{
	L4D360HybridButton *button = GetButton();
	if ( !IsEnabled() || !button || !button->IsEnabled() ) { vgui::surface()->PlaySound( "UI/menu_invalid.wav" ); return; }
	FlyoutMenu *flyout = GetFlyout();
	if ( !flyout ) return;
	if ( m_bNoBlindNavigation || flyout->IsBlindNavigationDisabled() ) { OnCommand( NULL ); return; }
	vgui::Button *original = flyout->FindChildButtonByCommand( GetCurrentSelection() );
	const char *command = m_SelectedCommand;
	vgui::Button *next = NULL;
	// Native follows the resource nav graph, not child order or a row-count cap.
	for ( ;; )
	{
		next = forward ? flyout->FindPrevChildButtonByCommand( command ) : flyout->FindNextChildButtonByCommand( command );
		if ( next ) next->OnThink();
		if ( !next || !next->GetCommand() || next == original || next->IsEnabled() ) break;
		command = ButtonCommand( next );
	}
	if ( next == original ) { vgui::surface()->PlaySound( "UI/menu_invalid.wav" ); return; }
	vgui::surface()->PlaySound( "UI/buttonclick.wav" );
	if ( next && next->GetCommand() ) SetCurrentSelection( ButtonCommand( next ) );
}
void DropDownMenu::OnKeyCodePressed( vgui::KeyCode code )
{
	if ( GetJoystickForCode( code ) != 0 ) return;
	const vgui::KeyCode key = GetBaseButtonCode( code );
	if ( m_bShowSelectedText && ( key == KEY_LEFT || key == KEY_XBUTTON_LEFT || key == KEY_XSTICK1_LEFT || key == KEY_XSTICK2_LEFT ) ) { ChangeSelection( true ); return; }
	if ( m_bShowSelectedText && ( key == KEY_RIGHT || key == KEY_XBUTTON_RIGHT || key == KEY_XSTICK1_RIGHT || key == KEY_XSTICK2_RIGHT ) ) { ChangeSelection( false ); return; }
	BaseClass::OnKeyCodePressed( code );
}
void DropDownMenu::OnMouseWheeled( int delta )
{
	if ( m_bShowSelectedText && delta ) ChangeSelection( delta < 0 );
}
void DropDownMenu::SetEnabled( bool enabled )
{
	if ( GetButton() ) { m_Button->SetEnabled( enabled ); m_Button->SetDropDownEnabled( enabled ); }
	BaseClass::SetEnabled( enabled );
}
void DropDownMenu::NavigateTo() { BaseClass::NavigateTo(); if ( GetButton() ) m_Button->NavigateTo(); }
void DropDownMenu::NavigateFrom() { BaseClass::NavigateFrom(); if ( GetButton() ) m_Button->NavigateFrom(); }
void DropDownMenu::NavigateToChild( vgui::Panel *child )
{
	if ( child == GetButton() && GetParent() ) GetParent()->NavigateToChild( this );
	else BaseClass::NavigateToChild( child );
}

FlyoutMenu *ConfigureChapterDropDown( DropDownMenu *dropDown, KeyValues *settings )
{
	if ( !dropDown || !settings ) return NULL;
	const char *mode = settings->GetString( "Game/mode", "coop" );
	const char *campaign = settings->GetString( "Game/campaign", "" );
	if ( !*mode || !*campaign ) return NULL;
	KeyValues *mission = g_TerrorModes.FindMission( campaign );
	KeyValues *chapters = mission ? mission->FindKey( CFmtStr( "Modes/%s", mode ) ) : NULL;
	const int count = chapters ? chapters->GetInt( "chapters", 0 ) : 0;
	if ( count <= 0 ) return NULL;
	const bool any = settings->GetBool( "Game/any_chapter_allowed", false );
	dropDown->SetFlyout( CFmtStr( "FlmChapter%d", clamp( count + ( any ? 1 : 0 ), 2, 15 ) ) );
	FlyoutMenu *flyout = dropDown->GetFlyout();
	if ( !flyout ) return NULL;
	for ( int i = 1; i <= 15; ++i )
	{
		vgui::Button *button = flyout->FindChildButtonByCommand( CFmtStr( "#L4D360UI_Chapter_%d", i ) );
		if ( !button ) continue;
		const char *text = chapters->GetString( CFmtStr( "%d/DisplayName", i ), NULL );
		button->SetText( text ? text : any ? "#L4D360UI_Chapter_Any" : "#L4D360UI_Chapter_Only1Avail" );
		button->SetEnabled( text != NULL || any );
	}
	return flyout;
}
