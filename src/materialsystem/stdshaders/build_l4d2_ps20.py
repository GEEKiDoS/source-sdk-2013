"""Build the L4D2 fixed ps_2_0 catalog that ShaderCompile2 -ver20b upgrades.

The catalog selects game-owned FXC sources. Their existing STATIC/DYNAMIC/SKIP
comments own the combo layout; [ps20b] directives do not belong to this profile.
Compile every surviving combo with Windows D3DCompile, emit the SDK combo-index
headers, and retain the existing VCS6/LZMA framing. No original bytecode is read.
Use --source NAME.fxc (repeatable) to build only selected catalog sources.
"""
from pathlib import Path
import argparse
import ctypes
import lzma
import math
import re
import struct
import zlib


class Macro(ctypes.Structure):
    _fields_ = [('Name', ctypes.c_char_p), ('Definition', ctypes.c_char_p)]


def take_blob(blob):
    if not blob:
        return b''
    vtable = ctypes.cast(blob, ctypes.POINTER(ctypes.POINTER(ctypes.c_void_p))).contents
    address = ctypes.WINFUNCTYPE(ctypes.c_void_p, ctypes.c_void_p)(vtable[3])(blob)
    size = ctypes.WINFUNCTYPE(ctypes.c_size_t, ctypes.c_void_p)(vtable[4])(blob)
    result = ctypes.string_at(address, size)
    ctypes.WINFUNCTYPE(ctypes.c_ulong, ctypes.c_void_p)(vtable[2])(blob)
    return result


def source_inputs(source, inputs):
    source = source.resolve()
    if source in inputs:
        return
    inputs[source] = source.read_bytes()
    for include in re.findall(rb'^\s*#\s*include\s+"([^"]+)"', inputs[source], re.M):
        source_inputs(source.parent / include.decode('ascii'), inputs)


def combo_metadata(inputs):
    static, dynamic, skips = [], [], []
    for source in inputs.values():
        for line in source.decode('utf-8-sig').splitlines():
            directive = re.fullmatch(r'\s*//\s*(STATIC|DYNAMIC|SKIP):\s*(.*?)\s*(?:\[([^\]]+)\])?\s*', line)
            if not directive:
                continue
            kind, text, profile = directive.groups()
            if profile == 'ps20b':
                continue
            if profile not in (None, 'ps20'):
                raise ValueError('Unsupported fixed-profile directive: ' + line)
            if kind == 'SKIP':
                skips.append(text)
                continue
            combo = re.fullmatch(r'"(\w+)"\s+"(\d+)\.\.(\d+)"', text)
            if not combo:
                raise ValueError('Unsupported combo directive: ' + line)
            name, low, high = combo.groups()
            (static if kind == 'STATIC' else dynamic).append((name, int(low), int(high)))
    return static, dynamic, skips


def combo_count(combos):
    return math.prod(high - low + 1 for name, low, high in combos)


def combo_values(combos, index):
    values = {}
    for name, low, high in combos:
        count = high - low + 1
        values[name] = low + index % count
        index //= count
    return values


def skip_expression(expression, values):
    expression = re.sub(r'\bdefined\s+\$(\w+)', lambda match: str(int(match[1] in values)), expression)
    expression = re.sub(r'\$(\w+)', lambda match: str(values.get(match[1], 0)), expression)
    if not re.fullmatch(r'[\d\s!<>=&|()]+', expression):
        raise ValueError('Unsupported SKIP expression: ' + expression)
    expression = expression.replace('&&', ' and ').replace('||', ' or ')
    expression = re.sub(r'!(?!=)', ' not ', expression)
    return bool(eval(expression.strip(), {'__builtins__': {}}, {}))


def combo_header(program, static, dynamic):
    lines = ['// Generated by build_l4d2_ps20.py from the FXC combo directives.', '#pragma once', '#include "shaderlib/cshader.h"']
    for kind, combos, stride in (('Static', static, combo_count(dynamic)), ('Dynamic', dynamic, 1)):
        classname = program + '_' + kind + '_Index'
        lines += ['class ' + classname, '{']
        for name, low, high in combos:
            lines.append('\tunsigned int m_n%s : %d;' % (name, max(1, (high - low).bit_length())))
        if combos:
            lines += ['#ifdef _DEBUG'] + ['\tbool m_b%s : 1;' % name for name, low, high in combos] + ['#endif']
        lines += ['public:']
        for name, low, high in combos:
            lines += ['\tvoid Set%s( int i )' % name, '\t{', '\t\tAssert( i >= %d && i <= %d );' % (low, high), '\t\tm_n%s = i - %d;' % (name, low), '#ifdef _DEBUG', '\t\tm_b%s = true;' % name, '#endif', '\t}', '']
        lines += ['\t%s()' % classname, '\t{']
        lines += ['\t\tm_n%s = 0;' % name for name, low, high in combos]
        if combos:
            lines += ['#ifdef _DEBUG'] + ['\t\tm_b%s = false;' % name for name, low, high in combos] + ['#endif']
        lines += ['\t}', '', '\tint GetIndex() const', '\t{']
        if combos:
            lines.append('\t\tAssert( %s );' % ' && '.join('m_b' + name for name, low, high in combos))
        terms = []
        for name, low, high in combos:
            terms.append('( %d * m_n%s )' % (stride, name))
            stride *= high - low + 1
        lines += ['\t\treturn ' + ' + '.join(terms + ['0']) + ';', '\t}', '};', '']
        checks = ' + '.join('psh_forgot_to_set_%s_%s' % (kind.lower(), name) for name, low, high in combos) or '1'
        lines += ['#define shader%sTest_%s %s' % (kind, program, checks), '']
    return ('\n'.join(lines) + '\n').encode('ascii')


def compressed_block(raw):
    payload = lzma.compress(raw, format=lzma.FORMAT_RAW, filters=[{'id': lzma.FILTER_LZMA1, 'dict_size': 1 << 18, 'lc': 3, 'lp': 0, 'pb': 2}])
    envelope = b'LZMA' + struct.pack('<II', len(raw), len(payload)) + b'\x5d' + struct.pack('<I', 1 << 18) + payload
    return struct.pack('<I', len(envelope) | 0x40000000) + envelope


def shader_cache(static_count, dynamic_count, groups, crc):
    blocks = []
    for static_id, programs in groups:
        block, pending = b'', b''
        for dynamic_id, program in programs:
            record = struct.pack('<II', dynamic_id, len(program)) + program
            if len(record) > 1 << 17:
                raise ValueError('Shader exceeds the SDK unpacked block size')
            if len(pending) + len(record) > 1 << 17:
                block += compressed_block(pending)
                pending = b''
            pending += record
        if pending:
            block += compressed_block(pending)
        blocks.append((static_id, block + struct.pack('<I', 0xffffffff)))
    offset = 28 + 8 * (len(blocks) + 1) + 4
    records = []
    for static_id, block in blocks:
        records.append((static_id, offset))
        offset += len(block)
    records.append((0xffffffff, offset))
    header = struct.pack('<7I', 6, static_count * dynamic_count, dynamic_count, 0, 0, len(records), crc)
    return header + b''.join(struct.pack('<II', *record) for record in records) + struct.pack('<I', 0) + b''.join(block for static_id, block in blocks)


def compile_shader(compiler, source, output_dir, include_dir):
    inputs = {}
    source_inputs(source, inputs)
    static, dynamic, skips = combo_metadata(inputs)
    static_count, dynamic_count = combo_count(static), combo_count(dynamic)
    source_bytes = inputs[source.resolve()]
    source_buffer = ctypes.create_string_buffer(source_bytes)
    program_name = re.sub(r'_ps2x$', '_ps20', source.stem)
    groups = []
    predefined = {'SHADER_MODEL_PS_2_0': 1, 'PC': 1, 'WIN32': 1}
    for static_id in range(static_count):
        programs = []
        for dynamic_id in range(dynamic_count):
            values = dict(predefined, **combo_values(static, static_id), **combo_values(dynamic, dynamic_id))
            if any(skip_expression(expression, values) for expression in skips):
                continue
            macros = (Macro * (len(values) + 1))(*(Macro(name.encode('ascii'), str(value).encode('ascii')) for name, value in values.items()), Macro(None, None))
            code, errors = ctypes.c_void_p(), ctypes.c_void_p()
            result = compiler.D3DCompile(source_buffer, len(source_bytes), str(source).encode(), macros, ctypes.c_void_p(1), b'main', b'ps_2_0', 1 << 15, 0, ctypes.byref(code), ctypes.byref(errors))
            diagnostic = take_blob(errors).decode('utf-8', 'replace')
            program = take_blob(code)
            if result:
                raise RuntimeError('%s static %d dynamic %d: D3DCompile failed %08x\n%s' % (source, static_id, dynamic_id, result & 0xffffffff, diagnostic))
            if diagnostic:
                print(diagnostic, end='' if diagnostic.endswith('\n') else '\n')
            if len(program) < 4 or struct.unpack_from('<I', program)[0] != 0xffff0200:
                raise RuntimeError('D3DCompile did not produce genuine ps_2_0 bytecode: ' + str(source))
            programs.append((dynamic_id, program))
        if programs:
            groups.append((static_id, programs))
    cache = shader_cache(static_count, dynamic_count, groups, zlib.crc32(source_bytes))
    header = combo_header(program_name, static, dynamic)
    output = output_dir / (program_name + '.vcs')
    include = include_dir / (program_name + '.inc')
    output.write_bytes(cache)
    include.write_bytes(header)
    print('Built %s and %s' % (output.name, include.name))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', type=Path, default=Path(__file__).resolve().parent)
    parser.add_argument('--output-dir', type=Path, required=True, help='VCS directory in the in-place mod, usually <mod>/shaders/fxc')
    parser.add_argument('--source', action='append', metavar='NAME.fxc', help='Build only this catalog source (repeatable); default: entire catalog')
    options = parser.parse_args()
    root = options.source_dir.resolve()
    output_dir = options.output_dir.resolve()
    catalog = [line.strip() for line in (root / 'l4d2_shaders_dx9_20.txt').read_text(encoding='ascii').splitlines() if line.strip() and not line.lstrip().startswith('//')]
    if options.source:
        selected = set(options.source)
        unknown = selected.difference(catalog)
        if unknown:
            parser.error('Sources are not in l4d2_shaders_dx9_20.txt: ' + ', '.join(sorted(unknown)))
        catalog = [source for source in catalog if source in selected]
    include_dir = root / 'include'
    output_dir.mkdir(parents=True, exist_ok=True)
    include_dir.mkdir(parents=True, exist_ok=True)
    compiler = ctypes.WinDLL('d3dcompiler_47.dll')
    compiler.D3DCompile.argtypes = [ctypes.c_void_p, ctypes.c_size_t, ctypes.c_char_p, ctypes.POINTER(Macro), ctypes.c_void_p, ctypes.c_char_p, ctypes.c_char_p, ctypes.c_uint, ctypes.c_uint, ctypes.POINTER(ctypes.c_void_p), ctypes.POINTER(ctypes.c_void_p)]
    compiler.D3DCompile.restype = ctypes.c_long
    for source in catalog:
        compile_shader(compiler, root / source, output_dir, include_dir)


if __name__ == '__main__':
    main()
